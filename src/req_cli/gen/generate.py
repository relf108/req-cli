"""
Generate python request modules from parsed OpenAPI endpoints.

Each endpoint group (tag) becomes one module; each operation becomes a plain
function calling :func:`req_cli.core.client.send`. Generated files are meant
to be edited - path params are function kwargs and query/body values are
literals you can tweak, exactly like the hand-written ``requests/`` files
these replace.
"""

from __future__ import annotations

import keyword
import re
from dataclasses import replace
from pathlib import Path
from pprint import pformat
from typing import Any

from req_cli.gen.openapi import Endpoint, Param

INDENT = "    "

_SAFE_NAME_RE = re.compile(r"[^0-9a-zA-Z_]")
_DEFAULT_BY_TYPE: dict[str, Any] = {"string": "", "integer": 0, "number": 0.0, "boolean": False}
"""Fallback defaults per schema type when a parameter declares no example."""


def _safe_name(name: str) -> str:
    safe = _SAFE_NAME_RE.sub("_", name)
    if not safe or safe[0].isdigit():
        safe = f"p_{safe}"
    if keyword.iskeyword(safe):
        safe = f"{safe}_"
    return safe


def _default_for(param: Param) -> Any:
    if param.example is not None:
        return param.example
    return _DEFAULT_BY_TYPE.get(param.schema_type, "")


def _literal(value: Any, indent_level: int) -> str:
    """Format *value* as a python literal, indented for nesting."""
    text = pformat(value, indent=1, width=72, sort_dicts=False)
    pad = INDENT * indent_level
    lines = text.splitlines()
    return "\n".join([lines[0], *(f"{pad}{line}" for line in lines[1:])])


def render_function(endpoint: Endpoint) -> str:
    """Render one endpoint as a python function calling ``send``."""
    args = []
    path_params_entries = []
    for param in endpoint.path_params:
        name = _safe_name(param.name)
        args.append(f"{name}: str = {_default_for(param)!r}")
        path_params_entries.append(f'"{param.name}": {name}')

    signature = ", ".join(args)
    doc = f"{endpoint.method} {endpoint.path}"
    if endpoint.summary:
        doc += f" - {endpoint.summary}"

    lines = [
        f"def {endpoint.function_name}({signature}) -> Result:",
        f'{INDENT}"""{doc}."""',
        f"{INDENT}return send(",
        f'{INDENT * 2}"{endpoint.method}",',
        f'{INDENT * 2}"{endpoint.path}",',
    ]
    if path_params_entries:
        lines.append(f"{INDENT * 2}path_params={{{', '.join(path_params_entries)}}},")
    if endpoint.query_params:
        lines.append(f"{INDENT * 2}params={{")
        for param in endpoint.query_params:
            comment = "" if param.required else "  # optional"
            lines.append(
                f'{INDENT * 3}"{param.name}": {_literal(_default_for(param), 3)},{comment}',
            )
        lines.append(f"{INDENT * 2}}},")
    if endpoint.body_example is not None:
        lines.append(f"{INDENT * 2}json={_literal(endpoint.body_example, 2)},")
    lines.append(f"{INDENT})")
    return "\n".join(lines)


def render_module(group: str, endpoints: list[Endpoint], spec_label: str) -> str:
    """Render a full module for one endpoint group."""
    seen: dict[str, int] = {}
    deduped = []
    for endpoint in endpoints:
        count = seen.get(endpoint.function_name, 0)
        seen[endpoint.function_name] = count + 1
        unique = replace(endpoint, function_name=f"{endpoint.function_name}_{count + 1}") if count else endpoint
        deduped.append(unique)

    header = (
        f'"""Requests for the `{group}` endpoints.\n'
        f"\n"
        f"Generated by req-cli from {spec_label}. Edit freely - defaults are\n"
        f'yours to tweak. Send with: req run {group}.<function>\n"""\n'
        f"\n"
        f"from req_cli.core.client import Result, send\n"
    )
    body = "\n\n\n".join(render_function(endpoint) for endpoint in deduped)
    return f"{header}\n\n{body}\n"


def generate_modules(endpoints: list[Endpoint], spec_label: str) -> dict[str, str]:
    """Group endpoints and render one module per group: ``{module_name: source}``."""
    groups: dict[str, list[Endpoint]] = {}
    for endpoint in endpoints:
        groups.setdefault(_safe_name(endpoint.group), []).append(endpoint)
    return {group: render_module(group, members, spec_label) for group, members in sorted(groups.items())}


def write_module(source: str, dest_dir: Path, module_name: str, *, overwrite: bool = False) -> Path:
    """Write one generated module into *dest_dir*, refusing to clobber by default."""
    dest_dir.mkdir(parents=True, exist_ok=True)
    dest = dest_dir / f"{module_name}.py"
    if dest.exists() and not overwrite:
        msg = f"{dest} already exists (pass overwrite to replace)"
        raise FileExistsError(msg)
    dest.write_text(source)
    return dest
